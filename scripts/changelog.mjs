#!/usr/bin/env node
// Generate CHANGELOG.md from git tags and Conventional Commit subjects.
//
// The file is never edited by hand. Each `vX.Y.Z` tag gets one section with
// the feat, fix, perf, and refactor commits since the previous tag; other
// types (docs, chore, ci, test, …) are left out because users do not see them.
//
// Usage:
//   node scripts/changelog.mjs                    print the changelog for the tags
//   node scripts/changelog.mjs --release 0.12.0   also add a section for HEAD
//   node scripts/changelog.mjs --release 0.12.0 --write   write CHANGELOG.md
//
// `scripts/sync-versions.sh` runs the `--release <version> --write` form, so
// the version-bump PR carries the new section.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const GROUPS = [
  ["feat", "Features"],
  ["fix", "Fixes"],
  ["perf", "Performance"],
  ["refactor", "Refactors"],
];
const SUBJECT_RE = /^([a-z]+)(?:\([^)]*\))?(!)?: (.+)$/;

/** Group commit subjects into changelog sections. Pure. */
export function groupSubjects(subjects) {
  const groups = new Map(GROUPS.map(([type]) => [type, []]));
  const breaking = [];
  for (const subject of subjects) {
    const match = SUBJECT_RE.exec(subject);
    if (!match) continue;
    const [, type, bang] = match;
    if (bang) breaking.push(subject);
    if (groups.has(type)) groups.get(type).push(subject);
  }
  return { groups, breaking };
}

/** Render one release section. Pure. */
export function renderSection(version, date, subjects, isFirst) {
  const { groups, breaking } = groupSubjects(subjects);
  const lines = [`## ${version} — ${date}`, ""];
  if (breaking.length > 0) {
    lines.push("### Breaking changes", "", ...breaking.map((s) => `- ${s}`), "");
  }
  for (const [type, title] of GROUPS) {
    const items = groups.get(type);
    if (items.length > 0) lines.push(`### ${title}`, "", ...items.map((s) => `- ${s}`), "");
  }
  if (lines.length === 2) {
    lines.push(isFirst ? "- First release from this repository." : "- No user-facing changes.", "");
  }
  return lines.join("\n");
}

/** Render the whole changelog from releases, newest first. Pure. */
export function renderChangelog(releases) {
  const header = [
    "# Changelog",
    "",
    "Generated by `scripts/changelog.mjs` from git tags and Conventional Commit",
    "subjects. Do not edit by hand. Only `feat`, `fix`, `perf`, and `refactor`",
    "commits are listed.",
    "",
  ].join("\n");
  const sections = releases.map((r, i) => renderSection(r.version, r.date, r.subjects, i === releases.length - 1));
  return `${header}\n${sections.join("\n")}`.replace(/\n+$/, "\n");
}

function git(root, args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf-8" }).trim();
}

function subjectsBetween(root, from, to) {
  const range = from ? `${from}..${to}` : to;
  let out;
  try {
    out = git(root, ["log", "--format=%s", range]);
  } catch {
    return []; // a repo with no commits yet
  }
  return out ? out.split("\n") : [];
}

/** Read releases from the repo's `v*` tags (plus an optional HEAD release). */
export function collectReleases(root, release, today) {
  let tags = [];
  try {
    tags = git(root, ["tag", "--list", "v*", "--sort=v:refname"]).split("\n").filter(Boolean);
  } catch {
    // not a git repo (a test fixture): no releases yet
  }
  const releases = [];
  let previous = null;
  for (const tag of tags) {
    releases.push({
      version: tag.replace(/^v/, ""),
      date: git(root, ["log", "-1", "--format=%as", tag]),
      subjects: subjectsBetween(root, previous, tag),
    });
    previous = tag;
  }
  // A tag for the release already exists (the publish job re-runs the bump):
  // its section is already in the list.
  if (release && !tags.includes(`v${release.replace(/^v/, "")}`)) {
    releases.push({ version: release.replace(/^v/, ""), date: today, subjects: subjectsBetween(root, previous, "HEAD") });
  }
  return releases.reverse();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const at = args.indexOf("--release");
  const release = at >= 0 ? args[at + 1] : undefined;
  if (at >= 0 && !release) {
    console.error("usage: changelog.mjs [--release <version>] [--write]");
    process.exit(2);
  }
  const root = fileURLToPath(new URL("..", import.meta.url));
  const today = new Date().toISOString().slice(0, 10);
  const text = renderChangelog(collectReleases(root, release, today));
  if (args.includes("--write")) {
    writeFileSync(join(root, "CHANGELOG.md"), text);
    console.log("✓ wrote CHANGELOG.md");
  } else {
    process.stdout.write(text);
  }
}
